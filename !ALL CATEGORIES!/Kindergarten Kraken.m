The Kindergarten Kraken - (15s · Cute Cinematic · Soft Pastel · HDR10 · 8K · 24fps)

🎨 VISUAL STYLE & LOOK

Ultra-cute Pixar-meets-storybook aesthetic.
Soft pastel palette: baby blues, lemon yellow, bubblegum pink accents.
Kraken’s body made of doodle-like glyphs that glow softly when emotional.
Classroom built from coral textures, jelly-windows, bioluminescent chalkboards.
Smooth micro-movements: tentacles sway gently, tiny particles drift in water.

🎥 CAMERA & LENS SETTINGS

Resolution: 8K Ultra HD (7680×4320)
Color space: DCI-P3 HDR10, 10-bit depth
Frame rate: 24 fps
Lens Package:
35mm anamorphic f/2.0 for warm close-ups with charming oval bokeh.
50mm f/1.8 for intimate emotional moments (heart drawing, glowing doodles).
20mm wide lens f/2.8 for classroom establishing shots.
Camera Motion: slow dolly, floaty underwater pans, gentle craning.
Focus Behavior: soft and dreamy, slight breathing, foreground particles drifting in/out.

🧪 FX, SIMULATIONS & MATERIAL BEHAVIOR
Water / Environment Physics

Light underwater sway applied to all elements (hair, fins, crayons, paper edges).

Floating micro-particles reacting to character movements.

Soft volumetric caustics on walls and desks.

Glow & Bioluminescence

Kraken's doodle-pattern glows gently when shy → stronger glow when proud.

Heart drawing emits soft gold sparkles and pulse-light.

Cute Classroom FX

Bubble bursts with soft refraction.

Glitter-like micro-algae confetti when the Kraken gets excited.

Stickers (gold stars) adhere with a tiny “pop” and sparkle.

Emotion FX

Blushing Kraken = saturation shift to deeper warm blue.

Kids cheering = small ripple waves of floating luminescent dots.

